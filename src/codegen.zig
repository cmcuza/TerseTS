//! Provides functions for generating Zig code at build time.
/// Currently it is used to generate integration tests for TerseTS.

// https://matklad.github.io/2025/04/19/things-zig-comptime-wont-do.html
// https://codeberg.org/ifreund/zig-wayland
// https://github.com/castholm/zigglgen/tree/master
// https://ziggit.dev/t/generating-tests-at-comptime/6473

const std = @import("std");
const ArrayList = std.ArrayList;
const Allocator = std.mem.Allocator;
const Random = std.Random;
const generators = @import("tester/generators.zig");
const Threaded = std.Io.Threaded;
const Clock = std.Io.Clock;

