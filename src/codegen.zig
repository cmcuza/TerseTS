//! Provides functions for generating Zig code at build time.
//! Currently it is used to generate integration tests for TerseTS.

const std = @import("std");

// TODO: Factor writing out into functions as much as possible.
// TODO: Move generating tests into a function to make it clear codegen is for other tasks as well.

const tersets = @import("tersets.zig");
const Method = tersets.Method;

const setups = @import("tester/setups.zig");
const generators = @import("tester/generators.zig");

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const cwd = std.Io.Dir.cwd();

    const integration_tests = try cwd.createFile(io, "src/integration_tests.zig", .{});
    defer integration_tests.close(io);

    var buffer: [8192]u8 = undefined; // undefined as the writer overwrites it anyway.
    var file_writer = integration_tests.writer(io, &buffer);
    const writer = &file_writer.interface;

    const header =
        \\// This file is generated by tester/codegen.zig and is not designed to be edited.
        \\const std = @import("std");
        \\const ArrayList = std.ArrayList;
        \\const testing = std.testing;
        \\
        \\const tersets = @import("tersets.zig");
        \\const setups = @import("tester/setups.zig");
        \\const generators = @import("tester/generators.zig");
        \\const tester_random = @import("tester/random.zig");
        \\const Method = tersets.Method;
        \\
        \\
    ;
    try writer.writeAll(header);

    for (std.enums.values(Method)) |method| {
        const configurations = setups.getConfiguration(method);
        const assert_function = setups.getAssertFunction(method);
        // An index is added to the test name instead of the configuration to not create very long names.
        for (configurations, 1..) |configuration, index| {
            for (generators.generator_names) |generator_name| {
                // The test allow compress() to return an UnsupportedInput error without failing the test
                // as some compression methods cannot handle all f64 values, however, compressing values
                // incorrectly is never acceptable, so any other error must always fail the test.
                const integration_test =
                    \\test "{s} {s} configuration {d}" {{
                    \\    const allocator = testing.allocator;
                    \\    const random = tester_random.getRandomGenerator();
                    \\   
                    \\    var uncompressed_values = ArrayList(f64).empty;
                    \\    defer uncompressed_values.deinit(allocator);
                    \\    try generators.{s}(allocator, &uncompressed_values, random);
                    \\   
                    \\    const configuration = "{s}";
                    \\    var compressed_values = tersets.compress(
                    \\        allocator,
                    \\        uncompressed_values.items,
                    \\        Method.{s},
                    \\        configuration,
                    \\    ) catch |err| switch (err) {{
                    \\        error.UnsupportedInput => return,
                    \\        else => return err,
                    \\    }};
                    \\    defer compressed_values.deinit(allocator);
                    \\   
                    \\    var decompressed_values = try tersets.decompress(
                    \\        allocator,
                    \\        compressed_values.items,
                    \\    );
                    \\    defer decompressed_values.deinit(allocator);
                    \\   
                    \\    try setups.{s}(uncompressed_values.items, decompressed_values.items);
                    \\}}
                    \\
                    \\
                ;
                try writer.print(integration_test, .{
                    @tagName(method),
                    generator_name,
                    index,
                    generator_name,
                    configuration,
                    @tagName(method),
                    assert_function,
                });
            }
        }
    }

    // try is not allowed in a defer expression.
    try writer.flush();
}
